export type PosterZone = {
  key: string;
  label: string;
  title: string;
  text: string;
  classQuestion?: string;
  tone: 'pine' | 'gold' | 'terracotta';
};

export type VisualMaterial = {
  key: string;
  kind: 'timeline' | 'poster';
  title: string;
  audience: string;
  description: string;
  minutes: number;
  events?: TimelineEvent[];
  zones?: PosterZone[];
};

const TONES: Record<PosterZone['tone'], string> = {
  pine: 'bg-pine-600',
  gold: 'bg-gold-500',
  terracotta: 'bg-terracotta-500',
};

export function toneClass(tone: PosterZone['tone']): string {
  return TONES[tone];
}

